import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

// 설치된 운영 의존성만 읽는다. 설치·네트워크 호출·환경 파일 로드는 하지 않는다.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = fs.existsSync(path.join(root, 'public')) ? 'public/licenses' : 'licenses';
const fallbackFile = path.join(root, 'licenses/upstream/manifest.json');
const fallbacks = fs.existsSync(fallbackFile) ? JSON.parse(fs.readFileSync(fallbackFile, 'utf8')) : [];
const result = spawnSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], {
  cwd: root, encoding: 'utf8', maxBuffer: 8 * 1024 * 1024,
});
if (result.status !== 0) throw new Error('npm ls 실패: 먼저 npm ci로 lockfile에 맞게 설치하세요.');
const sha = value => createHash('sha256').update(value).digest('hex');
const noticeName = /^(licen[cs]e|notice|copying|copyright)(?:[.\-_]|$)/i;
const packages = [];
const sections = [];
function noticeFiles(dir, relative = '') {
  const found = [];
  for (const entry of fs.readdirSync(path.join(dir, relative), { withFileTypes: true })) {
    if (entry.isSymbolicLink()) continue;
    const rel = path.join(relative, entry.name);
    if (entry.isDirectory() && entry.name !== 'node_modules' && !entry.name.startsWith('.')) {
      found.push(...noticeFiles(dir, rel));
    } else if (entry.isFile() && noticeName.test(entry.name)) {
      const data = fs.readFileSync(path.join(dir, rel));
      if (!data.includes(0)) found.push({ file: rel, text: data.toString('utf8') });
    }
  }
  return found;
}
for (const dir of [...new Set(result.stdout.trim().split(/\r?\n/))].sort()) {
  if (dir === root || !dir.startsWith(path.join(root, 'node_modules') + path.sep)) continue;
  const metaFile = path.join(dir, 'package.json');
  if (!fs.existsSync(metaFile)) continue;
  const meta = JSON.parse(fs.readFileSync(metaFile, 'utf8'));
  const row = {
    name: meta.name, version: meta.version, path: path.relative(root, dir),
    declaredLicense: meta.license ?? meta.licenses ?? null,
    author: meta.author ?? null, repository: meta.repository ?? null, notices: [],
  };
  const texts = noticeFiles(dir);
  if (!texts.length) {
    for (const name of fs.readdirSync(dir).filter(name => /^readme/i.test(name)).sort()) {
      const text = fs.readFileSync(path.join(dir, name), 'utf8');
      const match = /(?:^|\n)(?:#{1,6}\s*(?:licen[cs]e|copyright)[^\n]*|Licen[cs]e\r?\n[-=]+)\r?\n/i.exec(text);
      if (match && /Permission is hereby granted|Redistribution and use|GNU.*PUBLIC LICENSE/.test(text.slice(match.index))) {
        texts.push({ file: name + '#license-section', text: text.slice(match.index) });
      }
    }
  }
  for (const item of texts) {
    row.notices.push({ source: item.file, sha256: sha(item.text), kind: 'installed-package' });
    sections.push(`\n===== ${meta.name}@${meta.version} :: ${item.file} =====\n\n${item.text}\n`);
  }
  if (!texts.length) {
    const fallback = fallbacks.find(f => f.version === meta.version &&
      (f.name === meta.name || (f.prefix && meta.name.startsWith(f.prefix))));
    if (fallback) {
      const filename = path.resolve(root, 'licenses/upstream', fallback.file);
      if (!filename.startsWith(path.join(root, 'licenses/upstream') + path.sep)) throw new Error('잘못된 고지 경로');
      const text = fs.readFileSync(filename, 'utf8');
      if (sha(text) !== fallback.sha256) throw new Error('보충 고지 해시 불일치');
      row.notices.push({ source: fallback.source, sha256: sha(text), kind: fallback.kind });
      sections.push(`\n===== ${meta.name}@${meta.version} :: ${fallback.kind} =====\nSource: ${fallback.source}\n\n${text}\n`);
    }
  }
  if (!row.notices.length) {
    row.noticeStatus = 'package-declaration-only';
    sections.push(`\n===== ${meta.name}@${meta.version} :: package metadata =====\n${JSON.stringify(row, null, 2)}\n`);
  } else row.noticeStatus = 'text-included';
  packages.push(row);
}
const lock = fs.readFileSync(path.join(root, 'package-lock.json'));
const manifest = {
  scope: 'installed production dependency tree; optional packages depend on build platform',
  lockfileSha256: sha(lock), platform: process.platform, arch: process.arch, packages,
};
fs.mkdirSync(path.join(root, output), { recursive: true });
fs.writeFileSync(path.join(root, output, 'npm-runtime-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
fs.writeFileSync(path.join(root, output, 'npm-runtime-notices.txt'),
  'Third-party runtime notices\nGenerated by npm run notices from the installed production dependency tree.\n' +
  'Original notices are retained. Upstream supplements and package declarations are identified separately.\n' +
  'This file does not license Grimoire manuscripts or claim binary/source-offer compliance for every platform.\n' + sections.join(''));
console.log(`Runtime notice inventory: ${packages.length} packages, ${packages.filter(p => p.noticeStatus === 'package-declaration-only').length} declaration-only packages.`);
